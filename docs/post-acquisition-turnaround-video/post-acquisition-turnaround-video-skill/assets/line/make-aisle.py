"""Generates aisle-scene.svg: row 6's "go and see", a warehouse aisle at night in one-point perspective.
1920x1300, so a tilt-down (translateY 0 -> -220) and a slow push-in (scale 1 -> 1.06) never show an edge.
Run: python make-aisle.py"""
VX, VY = 960, 640          # vanishing point
W, H = 1920, 1300
D = [0.0, 0.55, 1.15, 1.85, 2.7, 3.7, 5.0, 6.6]   # depths, near -> far
def f(k): return 1 / (1 + D[k])
def X(side, k): return VX + side * 900 * f(k)      # rack face x at depth k
def Y(lvl, k): return VY + (lvl) * 700 * f(k)      # lvl: -1 top beam ... +0.9 floor
LEVELS = [-0.95, -0.42, 0.1, 0.62]                 # beam heights (relative)
FLOOR = 0.86
out = []
a = out.append
a(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">')
a('''  <!-- Row 6 "Vince went to the floor": the camera moves down into the aisle (Lean's "go and see").
       Animate the whole SVG: translateY(0 -> -220px) + scale(1 -> 1.06) over the line (origin 960px 640px).
       #ceilingLights: opacity flicker .9 <-> 1 (optional). Generated by make-aisle.py. -->
  <defs>
    <radialGradient id="aiGlow" cx="50%" cy="48%" r="55%"><stop offset="0" stop-color="#EAB62F" stop-opacity=".16"/><stop offset="1" stop-color="#EAB62F" stop-opacity="0"/></radialGradient>
    <linearGradient id="aiFloor" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#1f262a"/><stop offset="1" stop-color="#121517"/></linearGradient>
    <linearGradient id="aiCeil" x1="0" y1="1" x2="0" y2="0"><stop offset="0" stop-color="#1b2125"/><stop offset="1" stop-color="#121517"/></linearGradient>
    <radialGradient id="aiVig" cx="50%" cy="50%" r="70%"><stop offset=".55" stop-color="#121517" stop-opacity="0"/><stop offset="1" stop-color="#121517" stop-opacity=".95"/></radialGradient>
  </defs>''')
a(f'  <rect width="{W}" height="{H}" fill="#121517"/>')
# ceiling and floor planes
a(f'  <path d="M0 0 H{W} L{X(1,7)} {Y(-1.2,7)} H{X(-1,7)} Z" fill="url(#aiCeil)"/>')
a(f'  <path d="M0 {H} H{W} L{X(1,7)} {Y(FLOOR,7)} H{X(-1,7)} Z" fill="url(#aiFloor)"/>')
# floor lane markings (mustard, receding)
for k in range(0, 7, 1):
    y0, y1 = Y(FLOOR, k), Y(FLOOR, k + 1)
    if k % 2 == 0:
        a(f'  <path d="M{VX-14*f(k)*3} {y0+600*f(k)*0.5} L{VX+14*f(k)*3} {y0+600*f(k)*0.5} L{VX+14*f(k+1)*3} {y1+600*f(k+1)*0.5} L{VX-14*f(k+1)*3} {y1+600*f(k+1)*0.5} Z" fill="#EAB62F" opacity=".35"/>')
# far wall
a(f'  <rect x="{X(-1,7)}" y="{Y(-1.2,7)}" width="{X(1,7)-X(-1,7)}" height="{Y(FLOOR,7)-Y(-1.2,7)}" fill="#1b2125"/>')
a(f'  <rect x="{X(-1,7)}" y="{Y(-1.2,7)}" width="{X(1,7)-X(-1,7)}" height="{Y(FLOOR,7)-Y(-1.2,7)}" fill="url(#aiGlow)"/>')
# ceiling light strips
a('  <g id="ceilingLights">')
for k in range(0, 7):
    yc = Y(-1.12, k); w = 120 * f(k); h = 10 * f(k) + 2
    a(f'    <rect x="{VX-w/2}" y="{yc}" width="{w}" height="{h}" rx="{h/2}" fill="#F6D36B" opacity="{0.55+0.45*f(k)}"/>')
a('  </g>')
# racks, far to near so near ones overlap
BOX = ['#9C7650', '#B8926A', '#8a6a48', '#a88964', '#7d6346']
seed = [3]
def rnd():
    seed[0] = (seed[0] * 1103515245 + 12345) % 2**31; return seed[0] / 2**31
for k in range(6, -1, -1):
    for side in (-1, 1):
        xa, xb = X(side, k + 1), X(side, k)       # far edge, near edge of this bay
        # rack face (dark) for the bay
        a(f'  <path d="M{xa} {Y(-1,k+1)} L{xb} {Y(-1,k)} L{xb} {Y(FLOOR,k)} L{xa} {Y(FLOOR,k+1)} Z" fill="#192024"/>')
        # boxes/pallets on each level
        for li in range(len(LEVELS)):
            top = LEVELS[li]; bot = LEVELS[li + 1] if li + 1 < len(LEVELS) else FLOOR
            if rnd() < 0.12: continue           # an empty slot here and there
            fill_h = 0.55 + 0.35 * rnd()
            t = bot - (bot - top) * fill_h
            m = 0.08                             # margin along depth
            xa2 = xa + (xb - xa) * m; xb2 = xb - (xb - xa) * m
            ka, kb = k + 1 - m, k + m
            def yat(l, kk):  # interpolate depth
                fa = 1 / (1 + (D[int(kk)] + (D[min(int(kk)+1,7)] - D[int(kk)]) * (kk - int(kk))))
                return VY + l * 700 * fa
            col = BOX[int(rnd() * len(BOX))]
            a(f'  <path d="M{xa2} {yat(t,ka)} L{xb2} {yat(t,kb)} L{xb2} {yat(bot-0.02,kb)} L{xa2} {yat(bot-0.02,ka)} Z" fill="{col}" opacity=".78"/>')
            a(f'  <path d="M{xa2} {yat(t,ka)} L{xb2} {yat(t,kb)} L{xb2} {yat(t,kb)+4*f(k)} L{xa2} {yat(t,ka)+4*f(k+1)} Z" fill="#d8b688" opacity=".35"/>')
        # beams (muted rust) between the two uprights
        for l in LEVELS:
            th = 16 * f(k)
            a(f'  <path d="M{xa} {Y(l,k+1)} L{xb} {Y(l,k)} L{xb} {Y(l,k)+th} L{xa} {Y(l,k+1)+th*f(k+1)/f(k)} Z" fill="#a8550a"/>')
        # near upright of this bay
        uw = 34 * f(k)
        x0 = xb if side == 1 else xb - uw
        a(f'  <rect x="{x0}" y="{Y(-1,k)}" width="{uw}" height="{Y(FLOOR,k)-Y(-1,k)}" fill="#2f3d47"/>')
        a(f'  <rect x="{x0 + (uw*0.15 if side==1 else uw*0.7)}" y="{Y(-1,k)}" width="{uw*0.15}" height="{Y(FLOOR,k)-Y(-1,k)}" fill="#46586a"/>')
a(f'  <rect width="{W}" height="{H}" fill="url(#aiVig)"/>')
a('</svg>')
open('aisle-scene.svg', 'w', encoding='utf8').write('\n'.join(out))
print('wrote aisle-scene.svg')
